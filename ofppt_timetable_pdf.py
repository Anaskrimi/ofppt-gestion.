class _TTPdf(FPDF):
    FAM = "Arial"

    def txt(self, x, y, s, size=9, bold=False, italic=False, color=(0, 0, 0), align="L", w=None):
        self.set_font(self.FAM, ("B" if bold else "") + ("I" if italic else ""), size)
        self.set_text_color(*color)
        s = _c(s)
        sw = self.get_string_width(s)
        if align == "C":
            x = x + (w - sw) / 2 if w is not None else (self.w - sw) / 2
        elif align == "R" and w is not None:
            x = x + w - sw
        self.text(x, y, s)

    def fit(self, s, maxw, size, bold=False, mini=5.0):
        """Reduit la police puis tronque pour que le texte tienne dans maxw (mm)."""
        s = _c(s)
        st = "B" if bold else ""
        while True:
            self.set_font(self.FAM, st, size)
            if self.get_string_width(s) <= maxw or size <= mini:
                break
            size -= 0.5
        if self.get_string_width(s) > maxw:
            while len(s) > 1 and self.get_string_width(s + "..") > maxw:
                s = s[:-1]
            s = s.rstrip() + ".."
        return s, size

    def rrect(self, x, y, w, h, r=2.0, style="DF"):
        """Rectangle a coins arrondis (operateurs PDF bruts : fonctionne sur fpdf et fpdf2)."""
        k, H = self.k, self.h
        r = max(0.0, min(r, w / 2.0, h / 2.0))
        b = r * 0.5523

        def P(px, py):
            return f"{px * k:.2f} {(H - py) * k:.2f}"
        op = {"D": "S", "F": "f", "DF": "B", "FD": "B"}[style]
        o = self._out
        o(f"{P(x + r, y)} m")
        o(f"{P(x + w - r, y)} l")
        o(f"{P(x + w - r + b, y)} {P(x + w, y + r - b)} {P(x + w, y + r)} c")
        o(f"{P(x + w, y + h - r)} l")
        o(f"{P(x + w, y + h - r + b)} {P(x + w - r + b, y + h)} {P(x + w - r, y + h)} c")
        o(f"{P(x + r, y + h)} l")
        o(f"{P(x + r - b, y + h)} {P(x, y + h - r + b)} {P(x, y + h - r)} c")
        o(f"{P(x, y + r)} l")
        o(f"{P(x, y + r - b)} {P(x + r - b, y)} {P(x + r, y)} c")
        o(f"h {op}")

    def vdash(self, x, y1, y2, on=0.7, off=0.9):
        """Trait vertical pointille."""
        k, H = self.k, self.h
        self._out(f"[{on * k:.2f} {off * k:.2f}] 0 d")
        self.line(x, y1, x, y2)
        self._out("[] 0 d")


