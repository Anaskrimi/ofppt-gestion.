def _norm(t):
    import unicodedata
    t = unicodedata.normalize("NFD", str(t or "")).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", " ", t).strip()


def _etab_champs(D):
    """(direction, complexe, etablissement) lus dans l'onglet 'Etablissement' du logiciel."""
    try:
        from ofppt_timetable import TT_ETAB
        labels = {k: lab for k, lab in TT_ETAB}
    except Exception:
        labels = {}
    d = D.get("etab") or {}
    out = {"direction": "", "complexe": "", "etablissement": ""}
    for k, v in d.items():
        if not v:
            continue
        n = _norm(k) + " " + _norm(labels.get(k, ""))
        for cible in out:
            if cible in n and not out[cible]:
                out[cible] = str(v)
                break
        else:
            if not out["etablissement"] and _norm(k) in ("nom", "etab", "ista", "ecole", "nom etablissement"):
                out["etablissement"] = str(v)
    if not out["etablissement"]:                     # dernier recours : 1re valeur non deja utilisee
        deja = {out["direction"], out["complexe"]}
        out["etablissement"] = next((str(v) for v in d.values() if v and str(v) not in deja), "")
    et = get_etab() or {}
    if not out["direction"]:
        out["direction"] = et.get("direction") or DIRECTION_DEFAUT
    if not out["complexe"]:
        out["complexe"] = et.get("nom_court") or et.get("complexe") or ""
    return out["direction"], out["complexe"], out["etablissement"]


def _semaine(now):
    """Lundi -> samedi de la semaine en cours (dimanche : semaine suivante)."""
    from datetime import timedelta
    lundi = now.date() - timedelta(days=now.weekday())
    if now.weekday() == 6:
        lundi += timedelta(days=7)
    return lundi, lundi + timedelta(days=5)


def _annee_formation(now):
    a = now.year if now.month >= 8 else now.year - 1
    return f"{a}/{a + 1}"


